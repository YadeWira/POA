#!/usr/bin/env python3
"""Builds pas/poadict.inc: the Vorbis header dictionary.

The dictionary is the setup headers libvorbis writes at every quality
(-1..10), channel count (1, 2) and sample rate (8 to 48 kHz), plus the
start of the comment headers of common encoders. POA uses it to predict
the headers of a file (a match model), so a small file does not pay for
a 3-8 KB setup header that thousands of files share.

Usage: scripts/mkdict.py DIR_WITH_OGG_FILES
(the files made by: ffmpeg -f lavfi -i sine=f=440:d=0.2:r=R -ac C
 -c:a libvorbis -q:a Q s_R_C_Q.ogg, for the values above)
"""
import glob, hashlib, os, re, sys

def packets(d, n=3):
    p = 0; cur = b''; out = []
    while p < len(d) and len(out) < n:
        if d[p:p+4] != b'OggS':
            p += 1; continue
        ns = d[p+26]; lac = d[p+27:p+27+ns]; q = p + 27 + ns
        for l in lac:
            cur += d[q:q+l]; q += l
            if l < 255:
                out.append(cur); cur = b''
        p = q
    return out

def key(f):
    m = re.search(r's_(\d+)_(\d+)_(-?\d+)\.ogg$', f)
    return (int(m.group(1)), int(m.group(2)), int(m.group(3)))

seen = set(); parts = []
for f in sorted(glob.glob(os.path.join(sys.argv[1], 's_*.ogg')), key=key):
    s = packets(open(f, 'rb').read())[2]
    h = hashlib.sha1(s).digest()
    if h not in seen:
        seen.add(h); parts.append(s)
vendors = [b'Xiph.Org libVorbis I 20200704 (Reducing Environment)',
           b'Xiph.Org libVorbis I 20180316 (Now 100% fewer shells)',
           b'Xiph.Org libVorbis I 20150105 (\xe2\x9b\x84\xe2\x9b\x84\xe2\x9b\x84\xe2\x9b\x84)',
           b'Xiph.Org libVorbis I 20140122 (Turpak\xc3\xa4r\xc3\xa4jiin)',
           b'Xiph.Org libVorbis I 20120203 (Omnipresent)',
           b'Xiph.Org libVorbis I 20101101 (Schaufenugget)',
           b'Xiph.Org libVorbis I 20090709', b'Xiph.Org libVorbis I 20070622',
           b'Xiph.Org libVorbis I 20050304', b'Xiph.Org libVorbis I 20040629',
           b'Xiph.Org libVorbis I 20020717', b'Xiphophorus libVorbis I 20010813',
           b'Xiphophorus libVorbis I 20010225', b'Xiphophorus libVorbis I 20010615', b'AO; aoTuV b6.03 [20110424] (based on Xiph.Org\'s libVorbis)',
           b'AO; aoTuV [20110424] (based on Xiph.Org\'s libVorbis)',
           b'Lavf58.29.100', b'Lavf60.16.100', b'Lavf61.7.100', b'Lavf62.12.102',
           b'encoder=Lavc62.28.102 libvorbis', b'ENCODER=', b'TITLE=', b'ARTIST=', b'ALBUM=',
           b'DATE=', b'GENRE=', b'TRACKNUMBER=', b'COMMENT=', b'title=', b'artist=', b'album=']
blob = b''.join(b'\x03vorbis' + len(v).to_bytes(4, 'little') + v for v in vendors) + b''.join(parts)
out = os.path.join(os.path.dirname(__file__), '..', 'pas', 'poadict.inc')
with open(out, 'w') as o:
    o.write('{ Generated by scripts/mkdict.py: %d setup headers written by libvorbis\n'
            '  (BSD license, see NOTICE) and common comment-header vendor strings.\n'
            '  %d bytes. Part of the .poa format: changing it changes the format. }\n'
            % (len(parts), len(blob)))
    o.write('const\n  VORBIS_DICT: array[0..%d] of Byte = (\n' % (len(blob) - 1))
    for i in range(0, len(blob), 24):
        o.write('    ' + ','.join(str(b) for b in blob[i:i+24]) + (',' if i + 24 < len(blob) else '') + '\n')
    o.write('  );\n')
print(len(parts), 'setups,', len(blob), 'bytes ->', out)
